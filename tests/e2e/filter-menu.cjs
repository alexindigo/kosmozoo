const assert = require('node:assert/strict');
const fs = require('node:fs');
const { CDP, collectPageErrors } = require('./cdp.cjs');
const { workPath } = require('./paths.cjs');
const ENGINE = process.env.E2E_ENGINE ?? 'http://127.0.0.1:18260';
const FAKE = process.env.E2E_FAKE ?? 'http://127.0.0.1:18261';
const KZ = '(await import("/store/instance.js")).appStore';
(async () => {
  const page = await CDP.launch(9406, { windowSize: '1400,1000' });
  const errors = await collectPageErrors(page);
  const invoke = (id, args = {}) => page.evaluate(`(async()=>${KZ}.handles.invoke(${JSON.stringify(id)},${JSON.stringify(args)}))()`);
  const count = () => page.evaluate(`(async()=>${KZ}.state.entriesWithKnownSize().length)()`);
  const edit = (field, value) => invoke('feed.filter.edit', { field, value });
  const shot = async (name, selector) => {
    await page.evaluate('new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))');
    const clip = selector && await page.evaluate(`(()=>{const r=document.querySelector(${JSON.stringify(selector)}).getBoundingClientRect();return{x:r.x,y:r.y,width:r.width,height:r.height,scale:2}})()`);
    const image = await page.send('Page.captureScreenshot', { format: 'png', ...(clip ? { clip } : {}) });
    fs.writeFileSync(workPath(`artifacts/filter-menu-${name}.png`), Buffer.from(image.data, 'base64'));
  };
  try {
    fs.mkdirSync(workPath('artifacts'), { recursive: true });
    const publish = await fetch(FAKE + '/__test/activity', { method: 'POST', headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ publish: [{ name: 'filter-area/example.png', fixture: 'flux-basic.png', mtime: 2100000500 }] }) });
    assert(publish.ok);
    await page.goto(ENGINE + '/#fake#flux-basic.png');
    await page.poll(`(async()=>${KZ}.state.images.length>3000 && ${KZ}.state.pendingSizeCount()===0)()`, 60000);
    await invoke('source.refresh');
    await invoke('judgment.apply', { id: 'fake:flux-basic.png', intent: { type: 'set', patch: { vote: null, favorite: null, bookmark: null, notes: null } } });
    await page.poll(`document.querySelector('.card[data-name="flux-basic.png"] img')?.naturalWidth>0`, 30000);
    assert.equal(await page.evaluate(`!!document.querySelector('#filterMenu [aria-label="Parameter name"]')`), false, 'closed menu does not mount the metadata catalogue');
    await page.clickAt('#filterBtn');
    await page.poll(`document.querySelector('#filterMenu') && !document.querySelector('#filterMenu').hidden && document.activeElement.id==='filter'`);
    assert.equal(await page.evaluate(`document.activeElement.id`), 'filter');
    assert.equal(await page.evaluate(`!!document.querySelector('#clearFilters')`), false);
    assert.equal(await page.evaluate(`!!document.querySelector('#filterMenu [aria-label="Parameter comparison"]')`), false, 'no comparison without a parameter');
    assert.equal(await page.evaluate(`!!document.querySelector('#filter-parameterValue')`), false, 'no value without a parameter');
    await shot('empty'); await shot('empty-sections-2x', '#filterMenu');
    await page.key('Escape');
    await page.poll(`document.querySelector('#filterMenu').hidden && document.activeElement.id==='filterBtn'`);
    assert.equal(await page.evaluate(`!!document.querySelector('#filterMenu [aria-label="Parameter name"]')`), false, 'closing retires catalogue controls');
    console.log('ok opens menu, focuses visible filename, Escape closes and restores trigger');
    const baseline = await count();
    await page.clickAt('#filterBtn');
    await page.clickAt('#filter'); await page.send('Input.insertText', { text: 'flux-basic' });
    await page.poll(`(async()=>${KZ}.state.entriesWithKnownSize().length===1)()`);
    assert.equal(await page.evaluate(`new URLSearchParams(location.search).get('filter')`), 'flux-basic');
    assert.equal(await page.evaluate(`document.querySelector('#filterBtn').getAttribute('aria-pressed')`), 'true');
    await page.clickAt('#clearFilters');
    await edit('directory', 'a');
    await page.poll(`(async()=>{const s=${KZ};return s.state.entriesWithKnownSize().length>0 && s.state.entriesWithKnownSize().every(i=>{const f=s.state.images[i].filename;return f.slice(0,Math.max(0,f.lastIndexOf('/'))).toLowerCase().includes('a')})})()`);
    console.log('ok filename and directory filter the feed');
    await invoke('feed.filter.clear');
    await invoke('judgment.apply', { id: 'fake:flux-basic.png', intent: { type: 'set', patch: { vote: 'down', favorite: true, notes: { neg: 'blur test', pos: 'lovely' } } } });
    await page.clickAt('#filterMenu .down');
    await page.poll(`!!document.querySelector('.card[data-name="flux-basic.png"]')`);
    assert(await count() < baseline);
    await invoke('feed.filter.clear');
    await edit('negativeMode', 'contains'); await edit('negative', 'blur test');
    await page.poll(`(async()=>${KZ}.state.view().length===0)()`);
    await page.clickAt('#filterMenu .down');
    await page.poll(`(async()=>${KZ}.state.view().length===1)()`);
    console.log('ok negative notes and thumbs-down override persisted hiding');
    await invoke('feed.filter.clear');
    await edit('filename', 'flux-lora'); await edit('bookmark', 'true');
    const and = await count();
    await page.clickAt('#filterCombine button:nth-child(2)');
    await page.poll(`(async()=>${KZ}.state.feedFilter().mode==='or')()`);
    assert(await count() > and, 'OR admits a filename match without requiring bookmark');
    const orCount = await count();
    await edit('negativeMode', 'contains'); await edit('positiveMode', 'contains');
    assert.equal(await count(), orCount, 'empty feedback terms do not admit every entry in OR');
    assert.equal(await page.evaluate(`(async()=>${KZ}.state.filterSummary().length)()`), 2, 'incomplete rows are not set in the summary');
    await edit('negativeMode', 'any'); await edit('positiveMode', 'any');
    await edit('favorite', 'true');
    await page.poll(`document.querySelector('.card[data-name="flux-lora.png"] img')?.naturalWidth>0`, 30000);
    await page.evaluate(`document.querySelector('#filterMenu .favorite').focus()`);
    await shot('or-three'); await shot('or-sections-2x', '#filterMenu');
    await page.key('Escape'); await shot('header-on'); await shot('button-on-2x', '#filterBtn');
    const saved = await page.evaluate('location.href');
    const savedModel = await page.evaluate(`(async()=>${KZ}.state.feedFilter())()`);
    await invoke('entry.navigate', { source: 'fake', file: 'flux-lora.png' });
    await page.poll(`(async()=>${KZ}.state.filterSummary().length===0&&!location.search.includes('filter'))()`);
    await page.evaluate('history.back()');
    await page.poll(`location.href===${JSON.stringify(saved)}`);
    assert.deepEqual(await page.evaluate(`(async()=>${KZ}.state.feedFilter())()`), savedModel);
    console.log('ok AND/OR, URL and Back restore conditions');
    await invoke('feed.filter.clear');
    await invoke('feed.filter.toggle');
    const footerTop = await page.evaluate(`document.querySelector('.filter-footer').getBoundingClientRect().top`);
    const parameter = await page.evaluate(`(async()=>{const s=${KZ};for(const image of s.state.images) for(const node of image.meta?.nodes??[]) for(const [key,value] of Object.entries(node.inputs??{})) if(typeof value==='number') return{name:node.type+'.'+key,value:String(value)};return null})()`);
    assert(parameter, 'loaded metadata supplies a numeric parameter');
    await edit('parameter', parameter.name);
    await page.poll(`(async()=>${KZ}.state.entriesWithKnownSize().length>0)()`, 30000);
    assert.equal(await page.evaluate(`document.querySelector('#filterMenu [aria-label="Parameter comparison"]').value`), 'present');
    assert.equal(await page.evaluate(`!!document.querySelector('#filter-parameterValue')`), false, 'Present has no value field');
    assert(Math.abs(await page.evaluate(`document.querySelector('.filter-footer').getBoundingClientRect().top`) - footerTop) <= 1, 'comparison preserves footer allocation');
    await edit('parameterMode', 'equals'); await edit('parameterValue', parameter.value);
    assert.equal(await page.evaluate(`!!document.querySelector('#filter-parameterValue')`), true, 'Equals shows value');
    assert(Math.abs(await page.evaluate(`document.querySelector('.filter-footer').getBoundingClientRect().top`) - footerTop) <= 1, 'value field preserves footer allocation');
    await edit('parameterMode', 'contains');
    assert.equal(await page.evaluate(`!!document.querySelector('#filter-parameterValue')`), true, 'Contains shows value');
    await edit('parameter', '');
    assert.equal(await page.evaluate(`!!document.querySelector('#filterMenu [aria-label="Parameter comparison"], #filter-parameterValue')`), false, 'clearing parameter hides both controls despite retained Contains mode');
    assert(Math.abs(await page.evaluate(`document.querySelector('.filter-footer').getBoundingClientRect().top`) - footerTop) <= 1, 'clearing preserves footer allocation');
    await edit('parameter', parameter.name); await edit('parameterMode', 'equals');
    await page.poll(`(async()=>{const s=${KZ},name=${JSON.stringify(parameter.name)},value=${JSON.stringify(parameter.value)},p=name.lastIndexOf('.');return s.state.entriesWithKnownSize().length>0&&s.state.entriesWithKnownSize().every(i=>s.state.images[i].meta?.nodes.some(n=>n.type===name.slice(0,p)&&String(n.inputs?.[name.slice(p+1)])===value))})()`);
    console.log('ok parameter present/equals admits only loaded matching metadata');
    const counts = await page.evaluate(`(async()=>{const s=${KZ};return{n:s.state.entriesWithKnownSize().length,menu:document.querySelector('#filterMatchCount').textContent,footer:document.querySelector('.endoflist').textContent,rail:document.querySelector('.fr-total').textContent}})()`);
    assert(counts.menu.startsWith(counts.n + ' of '));
    assert(counts.footer.includes(String(counts.n)), JSON.stringify(counts));
    assert.equal(Number(counts.rail), counts.n);
    if (await page.evaluate(`document.querySelector('#filterMenu').hidden`)) await invoke('feed.filter.toggle');
    const geometry = await page.evaluate(`(()=>{const m=document.querySelector('#filterMenu'),r=m.getBoundingClientRect();return{bounded:r.left>=0&&r.right<=innerWidth&&r.top>=0&&r.bottom<=innerHeight,disabled:m.querySelectorAll('[disabled]').length,gaps:[...m.querySelectorAll('.chevron-slot')].map(s=>{const i=s.querySelector('svg').getBoundingClientRect(),b=s.getBoundingClientRect();return[Math.abs(i.left-b.left-(b.right-i.right)),Math.abs(i.top-b.top-(b.bottom-i.bottom))]})}})()`);
    assert(geometry.bounded && !geometry.disabled && geometry.gaps.every(g=>g.every(v=>v<=1)), JSON.stringify(geometry));
    await edit('negativeMode', 'contains');
    for (const selector of ['#filter', '#filter-directory', '#filterMenu .down', '#filterMenu .up', '#filterMenu .favorite', '#filterMenu .bookmark',
      '#filter-negative-mode', '#filter-negative', '#filter-positive-mode', '#filterMenu [aria-label="Search parameter names"]',
      '#filterMenu [aria-label="Parameter name"]', '#filterMenu [aria-label="Parameter comparison"]', '#filter-parameterValue', '#clearFilters']) {
      const name = selector.replace(/[^a-z0-9]+/gi, '-');
      await page.evaluate(`document.querySelector(${JSON.stringify(selector)}).focus()`);
      await shot('focus-' + name, '#filterMenu');
      const r = await page.evaluate(`document.querySelector(${JSON.stringify(selector)}).getBoundingClientRect().toJSON()`);
      await page.mouse('mouseMoved', r.x+r.width/2, r.y+r.height/2);
      await shot('hover-' + name, '#filterMenu');
    }
    assert.deepEqual(errors, []);
    await invoke('feed.filter.clear');
    await invoke('judgment.apply', { id: 'fake:flux-basic.png', intent: { type: 'set', patch: { vote: null, favorite: null, notes: {} } } });
    console.log('ok shared counts, bounded menu, uniform chevrons and zero page errors');
  } finally { await page.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
